export type StringKey = keyof typeof EN;

const TABLES: Record<string, Partial<Record<StringKey, string>>> = {
  en: EN,
};

let table: Partial<Record<StringKey, string>> = EN;

/** Takes the tag from getLanguage(), e.g. "pt-BR"; falls back to the base language, then English. */
export function setLanguage(tag: string): void {
  const lower = tag.toLowerCase();
  table = TABLES[lower] ?? TABLES[lower.split('-')[0] ?? ''] ?? EN;
  document.documentElement.lang = table === EN ? 'en' : lower;
}

/** Whether there are words for this key (data that names its own strings, like town goals). */
export function hasString(key: string): key is StringKey {
  return key in EN;
}

/** A string with {placeholders} filled in, e.g. t('day', { n: 3 }). */
export function t(key: StringKey, values: Record<string, string | number> = {}): string {
  const text: string | undefined = table[key] ?? EN[key];
  // A key made up at run time (`unit_${good}`) with no words yet shows as itself rather than
  // throwing: a missing string once stopped the whole game (the orders board, for apple orders).
  if (text === undefined) {
    if (!missing.has(key)) {
      missing.add(key);
      console.warn(`No words for "${key}"`);
    }
    return key;
  }
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
}

